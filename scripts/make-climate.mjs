// Monthly climate of Tunisia for the home map: for 24 towns, averages over 2015–2024 of the daily high and
// low, rainy days (≥ 1 mm), hours of sunshine, and the sea temperature off the coastal ones.
// Data: Open-Meteo (https://open-meteo.com), ERA5 reanalysis and the Open-Meteo marine model, CC BY 4.0.
// Usage: node scripts/make-climate.mjs   → src/content/climate.ts
import fs from 'node:fs';

const UA = { 'User-Agent': 'discover-tunisia-dev/0.1' };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const Y0 = 2015, Y1 = 2024;
// id, names, town, and a point a few km offshore for the sea temperature (null inland)
const TOWNS = [
  ['tunis', 'Tunis', 'Tunis', 'تونس', 36.80, 10.18, [36.86, 10.40]],
  ['bizerte', 'Bizerte', 'Bizerte', 'بنزرت', 37.27, 9.87, [37.36, 9.90]],
  ['tabarka', 'Tabarka', 'Tabarka', 'طبرقة', 36.95, 8.76, [37.02, 8.76]],
  ['kelibia', 'Kelibia', 'Kélibia', 'قليبية', 36.85, 11.10, [36.86, 11.20]],
  ['hammamet', 'Hammamet', 'Hammamet', 'الحمامات', 36.40, 10.61, [36.35, 10.72]],
  ['sousse', 'Sousse', 'Sousse', 'سوسة', 35.83, 10.63, [35.86, 10.73]],
  ['monastir', 'Monastir', 'Monastir', 'المنستير', 35.77, 10.83, [35.79, 10.95]],
  ['mahdia', 'Mahdia', 'Mahdia', 'المهدية', 35.50, 11.06, [35.53, 11.16]],
  ['sfax', 'Sfax', 'Sfax', 'صفاقس', 34.74, 10.76, [34.62, 11.05]],
  ['gabes', 'Gabès', 'Gabès', 'قابس', 33.88, 10.10, [33.93, 10.30]],
  ['djerba', 'Djerba', 'Djerba', 'جربة', 33.85, 10.95, [33.90, 11.10]],
  ['zarzis', 'Zarzis', 'Zarzis', 'جرجيس', 33.50, 11.11, [33.50, 11.26]],
  ['el-jem', 'El Jem', 'El Jem', 'الجم', 35.30, 10.71, null],
  ['kairouan', 'Kairouan', 'Kairouan', 'القيروان', 35.68, 10.10, null],
  ['zaghouan', 'Zaghouan', 'Zaghouan', 'زغوان', 36.40, 10.14, null],
  ['beja', 'Béja', 'Béja', 'باجة', 36.73, 9.18, null],
  ['jendouba', 'Jendouba', 'Jendouba', 'جندوبة', 36.50, 8.78, null],
  ['ain-draham', 'Aïn Draham', 'Aïn Draham', 'عين دراهم', 36.78, 8.69, null],
  ['le-kef', 'Le Kef', 'Le Kef', 'الكاف', 36.18, 8.71, null],
  ['sbeitla', 'Sbeitla', 'Sbeïtla', 'سبيطلة', 35.24, 9.12, null],
  ['gafsa', 'Gafsa', 'Gafsa', 'قفصة', 34.42, 8.78, null],
  ['tozeur', 'Tozeur', 'Tozeur', 'توزر', 33.92, 8.13, null],
  ['douz', 'Douz', 'Douz', 'دوز', 33.46, 9.02, null],
  ['tataouine', 'Tataouine', 'Tataouine', 'تطاوين', 32.93, 10.45, null],
];
async function get(url) {
  for (let t = 0; t < 6; t++) {
    try {
      const r = await fetch(url, { headers: UA });
      if (r.ok) return await r.json();
      console.warn(r.status, url.slice(0, 90)); await sleep(5000 * (t + 1));
    } catch (e) { console.warn(e.message); await sleep(5000 * (t + 1)); }
  }
  throw new Error('failed ' + url);
}
const r1 = (v) => Math.round(v * 10) / 10;
const out = [];
for (const [id, en, fr, ar, lat, lon, sea] of TOWNS) {
  const d = (await get(`https://archive-api.open-meteo.com/v1/archive?latitude=${lat}&longitude=${lon}&start_date=${Y0}-01-01&end_date=${Y1}-12-31&daily=temperature_2m_max,temperature_2m_min,precipitation_sum,sunshine_duration&timezone=Africa%2FTunis`)).daily;
  const acc = Array.from({ length: 12 }, () => ({ hi: 0, lo: 0, rain: 0, sun: 0, n: 0 }));
  d.time.forEach((t, i) => {
    const m = +t.slice(5, 7) - 1, a = acc[m];
    if (d.temperature_2m_max[i] == null) return;
    a.hi += d.temperature_2m_max[i]; a.lo += d.temperature_2m_min[i];
    a.rain += (d.precipitation_sum[i] ?? 0) >= 1 ? 1 : 0; a.sun += (d.sunshine_duration[i] ?? 0) / 3600; a.n++;
  });
  const days = [31, 28.25, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
  const row = {
    id, name: { en, fr, ar }, lat, lon,
    hi: acc.map((a) => r1(a.hi / a.n)), lo: acc.map((a) => r1(a.lo / a.n)),
    rain: acc.map((a, m) => Math.round((a.rain / a.n) * days[m])), sun: acc.map((a) => r1(a.sun / a.n)),
    sea: null,
  };
  if (sea) {
    const s = await get(`https://marine-api.open-meteo.com/v1/marine?latitude=${sea[0]}&longitude=${sea[1]}&start_date=${Y0}-01-01&end_date=${Y1}-12-31&hourly=sea_surface_temperature`);
    const sm = Array.from({ length: 12 }, () => [0, 0]);
    s.hourly.time.forEach((t, i) => { const v = s.hourly.sea_surface_temperature[i]; if (v == null) return; const m = +t.slice(5, 7) - 1; sm[m][0] += v; sm[m][1]++; });
    row.sea = sm.every(([, n]) => n > 100) ? sm.map(([v, n]) => r1(v / n)) : null;
  }
  out.push(row);
  console.log(id, 'Jul hi', row.hi[6], 'Jan hi', row.hi[0], 'sea Aug', row.sea?.[7] ?? '-', 'sun Jul', row.sun[6], 'rain Jan', row.rain[0]);
  await sleep(1500);
}
fs.writeFileSync('src/content/climate.ts', `// Generated by scripts/make-climate.mjs: averages over ${Y0}–${Y1}.
// Weather data by Open-Meteo.com (ERA5 reanalysis and the Open-Meteo marine model), CC BY 4.0.
import type { T3 } from '../i18n';

export interface Climate {
  id: string; name: T3; lat: number; lon: number;
  /** Average daily high and low (°C), days with at least 1 mm of rain, hours of sunshine a day, sea temperature (°C), by month. */
  hi: number[]; lo: number[]; rain: number[]; sun: number[]; sea: number[] | null;
}
export const CLIMATE: Climate[] = ${JSON.stringify(out)};
`);
console.log('written', out.length);

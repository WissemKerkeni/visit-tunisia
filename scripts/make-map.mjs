// Fetch Natural Earth (public domain) 1:50m countries, extract Tunisia (and the neighbouring land
// around it, clipped to a frame) and write SVG paths + projection constants to src/content/tunisia-map.ts.
import fs from 'node:fs';

const URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson';
const res = await fetch(URL, { headers: { 'User-Agent': 'TunisiaMonuments3D/0.1' } });
const data = await res.json();
const tun = data.features.find((f) => f.properties.ADM0_A3 === 'TUN');
if (!tun) throw new Error('Tunisia not found');

const polysOf = (f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates);
const polys = polysOf(tun);
let minLon = 180, maxLon = -180, minLat = 90, maxLat = -90;
for (const p of polys) for (const [lon, lat] of p[0]) {
  minLon = Math.min(minLon, lon); maxLon = Math.max(maxLon, lon);
  minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat);
}
const pad = 0.25;
minLon -= pad; maxLon += pad; minLat -= pad; maxLat += pad;
const kx = Math.cos(((minLat + maxLat) / 2) * Math.PI / 180);
const W = 400;
const scale = W / ((maxLon - minLon) * kx);
const H = Math.round((maxLat - minLat) * scale);
const proj = ([lon, lat]) => [((lon - minLon) * kx * scale).toFixed(1), ((maxLat - lat) * scale).toFixed(1)];
const toD = (rings) => rings.filter((r) => r.length > 2).map((r) => 'M' + r.map((c) => proj(c).join(',')).join('L') + 'Z').join('');

const d = toD(polys.map((p) => p[0]));

// neighbours, clipped to a frame around Tunisia (Sutherland–Hodgman against a lon/lat box)
const BOX = { lon0: 2.5, lon1: 17, lat0: 29.5, lat1: 39.5 };
function clip(ring) {
  const edges = [
    (p) => p[0] >= BOX.lon0, (p) => p[0] <= BOX.lon1, (p) => p[1] >= BOX.lat0, (p) => p[1] <= BOX.lat1,
  ];
  const cut = [
    (a, b) => [BOX.lon0, a[1] + ((b[1] - a[1]) * (BOX.lon0 - a[0])) / (b[0] - a[0])],
    (a, b) => [BOX.lon1, a[1] + ((b[1] - a[1]) * (BOX.lon1 - a[0])) / (b[0] - a[0])],
    (a, b) => [a[0] + ((b[0] - a[0]) * (BOX.lat0 - a[1])) / (b[1] - a[1]), BOX.lat0],
    (a, b) => [a[0] + ((b[0] - a[0]) * (BOX.lat1 - a[1])) / (b[1] - a[1]), BOX.lat1],
  ];
  let out = ring;
  for (let e = 0; e < 4; e++) {
    const inp = out; out = [];
    for (let i = 0; i < inp.length; i++) {
      const cur = inp[i], prev = inp[(i + inp.length - 1) % inp.length];
      const ci = edges[e](cur), pi = edges[e](prev);
      if (ci) { if (!pi) out.push(cut[e](prev, cur)); out.push(cur); } else if (pi) out.push(cut[e](prev, cur));
    }
    if (!out.length) break;
  }
  return out;
}
const NEIGHBOURS = { DZA: 'algeria', LBY: 'libya', ITA: 'italy', MLT: 'malta' };
const neighbours = [];
for (const f of data.features) {
  const id = NEIGHBOURS[f.properties.ADM0_A3];
  if (!id) continue;
  const rings = polysOf(f).map((p) => clip(p[0])).filter((r) => r.length > 2);
  if (rings.length) neighbours.push({ id, d: toD(rings) });
}

const out = `// Generated by scripts/make-map.mjs from Natural Earth 1:50m (public domain).
export const MAP_W = ${W};
export const MAP_H = ${H};
export const TUNISIA_PATH = '${d}';
/** Neighbouring land around Tunisia (clipped to lon ${BOX.lon0}–${BOX.lon1}, lat ${BOX.lat0}–${BOX.lat1}), same projection. */
export const NEIGHBOUR_PATHS: { id: string; d: string }[] = ${JSON.stringify(neighbours)};
/** Map units per degree of latitude (1° ≈ 111 km). */
export const UNITS_PER_DEG_LAT = ${scale};
export function project(lat: number, lon: number): [number, number] {
  return [(lon - ${minLon}) * ${kx} * ${scale}, (${maxLat} - lat) * ${scale}];
}
`;
fs.mkdirSync('src/content', { recursive: true });
fs.writeFileSync('src/content/tunisia-map.ts', out);
console.log('polygons', polys.length, 'size', W, 'x', H, 'neighbours', neighbours.map((n) => `${n.id} ${n.d.length}`).join(', '));
